import Foundation
import CoreData
import os.log

extension CryptoManager {

    // MARK: - Locked Core Operation Wrappers

    // All methods below acquire coreLock before touching orchestratorCore.
    // External callers MUST use these instead of accessing orchestratorCore directly.

    /// Sign binary data using the device Ed25519 identity key.
    func signBundleData(_ bundleData: Data) throws -> Data {
        coreLock.lock()
        defer { coreLock.unlock() }
        guard let core = orchestratorCore else { throw CryptoManagerError.coreNotInitialized }
        return try core.signBundleData(bundleDataJson: bundleData)
    }

    // MARK: - Hybrid PQ Identity Signatures (Ed25519 + ML-DSA-65)
    //
    // The hybrid signature private key is owned by the Rust core (KeyManager + CFE).
    // All generation, signing and public key derivation go through OrchestratorCore.
    // The "when to generate / sign SPK / publish" policy remains in Swift services.
    //
    // Client and server share the SAME implementation (RustCrypto ml-dsa, seed-based),
    // so every format is byte-identical and signatures cross-verify.

    /// Returns the device hybrid identity public key (1984 bytes).
    /// The key is ensured inside the core on first use.
    @discardableResult
    func ensureHybridIdentityPublicKey() throws -> Data {
        coreLock.lock()
        defer { coreLock.unlock() }

        guard let core = orchestratorCore else {
            throw CryptoManagerError.coreNotInitialized
        }

        // Migration from legacy separate keychain item (if any).
        if core.hybridSignaturePublicKey() == nil,
           let oldPriv = KeychainManager.shared.loadHybridSigPrivateKey(),
           !oldPriv.isEmpty {
            do {
                try core.importHybridSignaturePrivateKey(privBytes: oldPriv)
                // Fail-closed: until the CFE blob is durably written, the legacy item is the
                // ONLY copy of this key. Deleting it after an unchecked persist destroyed the
                // device's hybrid identity outright. Keep it and let the next call retry —
                // the key stays reachable either way, so this is not fatal to the caller.
                if persistCoreState() {
                    KeychainManager.shared.deleteHybridSigPrivateKey()
                    Log.info("Migrated legacy hybrid sig private key into core CFE", category: "CryptoManager")
                } else {
                    Log.error("Hybrid key migration: CFE persist failed — legacy Keychain item kept, will retry", category: "CryptoManager")
                }
            } catch {
                Log.error("Hybrid key migration import failed (will retry): \(error)", category: "CryptoManager")
            }
        }

        let existedBeforeCall = core.hybridSignaturePublicKey() != nil
        let pub = try core.ensureHybridSignatureKey()
        // Capture the hybrid key (if this call just generated it) into the CFE blob.
        if !persistCoreState() {
            // A key that already existed is durable regardless of this write (it came from the
            // CFE blob, or from the legacy item still in the Keychain above) — log and continue.
            guard existedBeforeCall else {
                // A key generated by this very call lives only in memory. Releasing the public
                // half would let the caller publish it and set the published flag, while the
                // next launch reloads a core without it and generates a different key — the
                // server would stay pinned to an identity this device can no longer prove.
                Log.error("Hybrid identity key generated but CFE persist failed — withholding public key so it is not published", category: "CryptoManager")
                throw CryptoManagerError.keyStatePersistFailed
            }
            Log.error("persistCoreState failed after ensureHybridSignatureKey (key already durable, continuing)", category: "CryptoManager")
        }
        return Data(pub)
    }

    /// The device hybrid identity public key if one exists in core, else nil.
    func hybridIdentityPublicKey() -> Data? {
        coreLock.lock()
        defer { coreLock.unlock() }
        guard let core = orchestratorCore else { return nil }
        return core.hybridSignaturePublicKey().map { Data($0) }
    }

    /// Signs a message with the device hybrid identity key (core-owned).
    /// The secret stays in the core — never `getSigningKeyBytes`.
    func signHybrid(_ message: Data) throws -> Data {
        coreLock.lock()
        defer { coreLock.unlock() }
        guard let core = orchestratorCore else { throw CryptoManagerError.coreNotInitialized }
        return try core.signHybrid(message: message)
    }

    /// Verifies a hybrid signature against a peer's hybrid public key. Both the
    /// Ed25519 and ML-DSA-65 components must validate. Stateless.
    func verifyHybrid(publicKey: Data, message: Data, signature: Data) throws -> Bool {
        return try hybridVerify(publicKey: publicKey, message: message, signature: signature)
    }

    // MARK: - Core-delegated hybrid helpers (fully switched after bindings regen)

    func buildX3dhSignMessage(suiteId: UInt8, publicKey: Data) -> Data {
        coreLock.lock()
        defer { coreLock.unlock() }
        guard let core = orchestratorCore else {
            // Should not happen in normal use after core init; fall back to known bytes
            var m = Data("KonstruktX3DH-v1".utf8)
            m.append(0x00)
            m.append(suiteId)
            m.append(publicKey)
            return m
        }
        return core.buildX3dhSignMessage(suiteId: suiteId, publicKey: publicKey)
    }

    func buildHybridIdentityBindMessage(hybridPublic: Data) -> Data {
        coreLock.lock()
        defer { coreLock.unlock() }
        guard let core = orchestratorCore else {
            var m = Data("KonstruktHybridId-v1".utf8)
            m.append(hybridPublic)
            return m
        }
        return core.buildHybridIdentityBindMessage(hybridPublicKey: hybridPublic)
    }

    /// High-level: ensure hybrid key (if needed) + produce hybrid signature over the
    /// standard X3DH prekey sign-message.
    func signHybridPrekey(suiteId: UInt8, publicKey: Data) throws -> Data {
        coreLock.lock()
        defer { coreLock.unlock() }
        guard let core = orchestratorCore else { throw CryptoManagerError.coreNotInitialized }
        let sig = try core.signHybridPrekey(suiteId: suiteId, publicKey: publicKey)
        return Data(sig)
    }

    /// Returns the hybrid signatures (if hybrid identity is published) over the
    /// *current* classic and Kyber SPKs. This is the data the publish/rotation
    /// paths need. Moving this here lifts logic from HybridIdentityService.
    @MainActor
    func currentHybridPrekeySignatures() -> (spk: Data?, kyber: Data?) {
        // Rotation path: attach the SPK/Kyber hybrid signatures only once the hybrid identity key is
        // already published server-side (rotation does NOT re-upload that key, so the server would
        // have nothing to verify these against otherwise).
        guard HybridIdentityService.isHybridIdentityPublished else { return (nil, nil) }
        return hybridPrekeySignaturesForPublish()
    }

    /// Hybrid SPK + Kyber-SPK signatures for the ATOMIC publish path
    /// (`HybridIdentityService.publish`), which uploads the hybrid identity key in the SAME request.
    /// The server (`key-service store_hybrid_identity`) verifies these against that same-request key,
    /// so there is NO "must already be published" precondition here — unlike
    /// `currentHybridPrekeySignatures()`, this does not gate on `isHybridIdentityPublished`. Gating
    /// the publish path was the bug: the first-ever publish sent nil SPK signatures, shipping a
    /// "hybrid key present, SPK signature missing" bundle that peers hard-reject → classic X3DH.
    func hybridPrekeySignaturesForPublish() -> (spk: Data?, kyber: Data?) {
        let spk: Data? = (try? localBundlePublicKeys().signedPrekeyPublic).flatMap { pub in
            try? signHybridPrekey(suiteId: 0x01, publicKey: pub)
        }
        // The Kyber SPK's hybrid signature is the core's, made when the key was: it covers the
        // signed `created_at` as well as the key (PQXDH v2), so it cannot be produced from the
        // public key here.
        let kyber: Data? = (try? currentKyberSpkUpload()).map { $0.hybridSignature }
        return (spk, kyber)
    }

    /// Rotate the signed pre-key and return the new public material.
    func rotateSignedPrekey() throws -> RotatedSpkBundle {
        coreLock.lock()
        defer { coreLock.unlock() }
        guard let core = orchestratorCore else { throw CryptoManagerError.coreNotInitialized }
        return try core.rotateSignedPrekey()
    }

    /// Generate a batch of fresh X25519 OTPKs.
    func generateOneTimePrekeys(count: UInt32) throws -> [OtpkPair] {
        coreLock.lock()
        defer { coreLock.unlock() }
        guard let core = orchestratorCore else { throw CryptoManagerError.coreNotInitialized }
        return try core.generateOneTimePrekeys(count: count)
    }

    /// Export all OTPK private keys as a CFE blob.
    func exportOneTimePrekeys() throws -> Data {
        coreLock.lock()
        defer { coreLock.unlock() }
        guard let core = orchestratorCore else { throw CryptoManagerError.coreNotInitialized }
        return try core.exportOneTimePrekeys()
    }

    /// Number of OTPKs currently held in the Rust core.
    func oneTimePrekeyCount() -> UInt32 {
        coreLock.lock()
        defer { coreLock.unlock() }
        return orchestratorCore?.oneTimePrekeyCount() ?? 0
    }

    /// Prune OTPK private keys with id below `minKeepId`; returns the number removed.
    /// Only valid right after a successful replace-all upload, when the server set is
    /// known to be exactly the new batch — see `OtpkReplenishmentService`.
    func pruneOneTimePrekeys(below minKeepId: UInt32) -> UInt32 {
        coreLock.lock()
        defer { coreLock.unlock() }
        return orchestratorCore?.pruneOneTimePrekeysBelow(minKeepId: minKeepId) ?? 0
    }

    // MARK: - Kyber prekeys (ML-KEM-1024, PQXDH v2)
    //
    // The core generates, signs and holds them; the seeds never leave it. Every call that changes
    // them is followed by `KyberPrekeyService.persist()`, as with the classic OTPKs.

    func generateKyberOneTimePrekeys(count: UInt32) throws -> [KyberPrekeyUpload] {
        coreLock.lock()
        defer { coreLock.unlock() }
        guard let core = orchestratorCore else { throw CryptoManagerError.coreNotInitialized }
        return try core.generateKyberOneTimePrekeys(count: count)
    }

    func kyberOneTimePrekeyCount() -> UInt32 {
        coreLock.lock()
        defer { coreLock.unlock() }
        return orchestratorCore?.kyberOneTimePrekeyCount() ?? 0
    }

    /// Same rule as `pruneOneTimePrekeys(below:)`: only after a replace-all upload.
    func pruneKyberOneTimePrekeys(below minKeepId: UInt32) -> UInt32 {
        coreLock.lock()
        defer { coreLock.unlock() }
        return orchestratorCore?.pruneKyberOneTimePrekeysBelow(minKeepId: minKeepId) ?? 0
    }

    /// The Kyber SPK to upload with a rotation. Asked again before commit/rollback, it returns the
    /// same key, so a retried upload uploads the same key.
    func beginKyberSpkRotation() throws -> KyberPrekeyUpload {
        coreLock.lock()
        defer { coreLock.unlock() }
        guard let core = orchestratorCore else { throw CryptoManagerError.coreNotInitialized }
        return try core.beginKyberSpkRotation()
    }

    /// The server confirmed the Kyber SPK from `beginKyberSpkRotation`. False if none was pending.
    @discardableResult
    func commitKyberSpkRotation() -> Bool {
        coreLock.lock()
        defer { coreLock.unlock() }
        return orchestratorCore?.commitKyberSpkRotation() ?? false
    }

    /// The server refused the pending Kyber SPK outright (it stored nothing): forget it, so the
    /// next rotation starts from a fresh key instead of resending one the server will refuse again.
    func rollbackKyberSpkRotation() {
        coreLock.lock()
        defer { coreLock.unlock() }
        orchestratorCore?.rollbackKyberSpkRotation()
    }

    /// The current Kyber SPK's upload record, or nil before the first commit.
    func currentKyberSpkUpload() throws -> KyberPrekeyUpload? {
        coreLock.lock()
        defer { coreLock.unlock() }
        guard let core = orchestratorCore else { throw CryptoManagerError.coreNotInitialized }
        return try core.currentKyberSpkUpload()
    }

    /// Decapsulate with our Kyber prekey `keyId` (0 = the current SPK). History transfer only —
    /// the session handshake decapsulates inside the core.
    func kyberPrekeyDecapsulate(keyId: UInt32, ciphertext: Data) throws -> Data {
        coreLock.lock()
        defer { coreLock.unlock() }
        guard let core = orchestratorCore else { throw CryptoManagerError.coreNotInitialized }
        return try core.kyberPrekeyDecapsulate(keyId: keyId, ciphertext: ciphertext)
    }

    func exportKyberPrekeys() throws -> Data {
        coreLock.lock()
        defer { coreLock.unlock() }
        guard let core = orchestratorCore else { throw CryptoManagerError.coreNotInitialized }
        return try core.exportKyberPrekeys()
    }

    /// Export a session's wire bytes (for session init completed notification).
    func exportSession(contactId: String) throws -> Data {
        coreLock.lock()
        defer { coreLock.unlock() }
        guard let core = orchestratorCore else { throw CryptoManagerError.coreNotInitialized }
        guard let resolved = SessionAddressing.asDevice(contactId) else {
            throw CryptoManagerError.sessionNotFound
        }
        return try core.exportSession(contactId: resolved)
    }
}
